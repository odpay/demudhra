#!/usr/bin/env python3
"""Generate checked-in offline artifacts. Run with --check in CI."""
import argparse
import collections
import hashlib
import json
from pathlib import Path
import re
import os
import tempfile
import subprocess

ROOT = Path(__file__).resolve().parents[1]
GROUP_COUNTS = {'default-root': 1, 'default-intermediate': 16,
                'all-emudhra-root': 25, 'opt-in-cross-sign': 1}


def platform_script(platform, *, release=True):
    parts = [(ROOT / 'src' / name).read_text() for name in
             ('common.sh', 'stores.sh', f'{platform}.sh')]
    source = ('#!/bin/sh\n# Generated by tools/generate.py. Edit src/ then regenerate.\n'
              f'platform={platform}\n' + '\n'.join(parts) + '\nmain "$@"\n')
    if release:
        source = re.sub(r'^\s*# DEMUDHRA_TEST_ONLY_BEGIN\n.*?^\s*# DEMUDHRA_TEST_ONLY_END\n',
                        '', source, flags=re.M | re.S)
        # Test-root branches become unreachable in releases. Remove their input
        # expansions as well so inherited environment variables cannot activate them.
        source = re.sub(r'\$\{DEMUDHRA_TEST_[A-Z_]+(?::-[^}]*)?\}', '${root:+}', source)
        source = re.sub(r'\$DEMUDHRA_TEST_[A-Z_]+\b', '${root:+}', source)
        if 'DEMUDHRA_TEST' in source:
            raise ValueError('Unstripped test hook in release script')
    return source


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='fail if generated artifacts differ')
    parser.add_argument('--verify-pems', action='store_true', help='recompute every supplied DER hash')
    args = parser.parse_args()
    certs = json.loads((ROOT / 'data/certs.json').read_text())
    assert len(certs) == sum(GROUP_COUNTS.values())
    assert collections.Counter(c['group'] for c in certs) == GROUP_COUNTS
    assert len({c['sha256'] for c in certs}) == len(certs)
    lines = ['# sha256\tgroup\tsubject\tsource_url\n']
    for cert in certs:
        assert re.fullmatch('[0-9a-f]{64}', cert['sha256'])
        fields = [cert['sha256'], cert['group'], cert['subject'], cert['source_urls'][0]]
        assert all(not any(ch in field for ch in '\t\r\n') for field in fields)
        lines.append('\t'.join(fields) + '\n')
        if args.verify_pems:
            der = subprocess.check_output(['openssl', 'x509', '-in',
                str(ROOT / 'tests/fixtures' / cert['pem_path']), '-outform', 'DER'], timeout=45)
            assert hashlib.sha256(der).hexdigest() == cert['sha256'], cert['id']
    outputs = {ROOT / 'data/fingerprints.tsv': ''.join(lines)}
    for platform in ('linux', 'macos'):
        outputs[ROOT / f'demudhra-{platform}.sh'] = platform_script(platform)
    for path, content in outputs.items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f'OUT OF SYNC: {path.relative_to(ROOT)}; run python3 tools/generate.py')
        else:
            with tempfile.NamedTemporaryFile(mode='w', dir=path.parent, prefix='.generate-', delete=False) as staged:
                staged.write(content)
                staged_path = Path(staged.name)
            staged_path.chmod(0o755 if path.suffix == '.sh' else 0o644)
            os.replace(staged_path, path)
    print(f'PASS: {len(certs)} verified metadata rows; {len(outputs)} generated artifacts' +
          ('; DER hashes verified' if args.verify_pems else ''))


if __name__ == '__main__':
    main()
